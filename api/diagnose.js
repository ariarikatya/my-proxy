// api/diagnose.js
export default async function handler(req, res) {
    // 🔥 1. ДОБАВЛЯЕМ CORS ЗАГОЛОВКИ, ЧТОБЫ БРАУЗЕР НЕ БЛОКИРОВАЛ ЗАПРОСЫ
    res.setHeader('Access-Control-Allow-Credentials', true);
    res.setHeader('Access-Control-Allow-Origin', '*'); // Разрешаем запросы отовсюду
    res.setHeader('Access-Control-Allow-Methods', 'GET,OPTIONS,PATCH,DELETE,POST,PUT');
    res.setHeader('Access-Control-Allow-Headers', 'X-CSRF-Token, X-Requested-With, Accept, Accept-Version, Content-Length, Content-MD5, Content-Type, Date, X-Api-Version, Authorization');

    // 🔥 2. ОБРАБАТЫВАЕМ ПРОВЕРКУ БРАУЗЕРА (OPTIONS) — ОШИБКА 405 УЙДЕТ ТУТ
    if (req.method === 'OPTIONS') {
        return res.status(200).end(); // Просто отвечаем «ОК» на проверку браузера
    }

    // Твой текущий код обработки POST запроса:
    if (req.method !== 'POST') {
        return res.status(405).json({ error: 'Method not allowed' });
    }

    try {
        const { image } = req.body;
        if (!image) {
            return res.status(400).json({ error: 'Image data is required' });
        }

        const systemInstructions = `Ты — строгий эксперт, ведущий агроном и фитопатолог ландшафтной компании 'Анемон АГРО'. Твоя задача — дать профессиональный, исчерпывающий клинический отчёт по фотографии любого присланного растения (это может быть комнатный цветок, садовое дерево, кустарник, газонная трава или сорняк).

КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО:
- Писать приветствия ("Здравствуйте!", "Приветствую" и т.д.).
- Вести дружескую беседу и задавать вопросы в конце.
- Ограничиваться общими фразами.

ИНСТРУКЦИЯ ПО АНАЛИЗУ:
Внимательно оценивай ключевые маркеры на фото: тип растения (хвойное, лиственное, травянистое, цветущее), форму и цвет листьев/хвои/бутонов, состояние коры, стеблей или приствольной зоны. Сверяй эти признаки со своей базой данных фитопатологий для конкретного найденного семейства.

Структура отчёта (Выдай строго 4 раздела, заголовки выделяй **):

**1. Определение растения:** Напиши конкретное русское общепринятое название растения и его точный ботанический род/семейство. Формат вывода: [Популярное название / Обиходное имя (Род или Семейство)]. Не пиши размыто "это какой-то куст". Если идентификация затруднена, укажи 2-3 наиболее вероятных конкретных вида.

**2. Анализ здоровья и симптомы:** Опиши текущее состояние растения на фото (наличие пятен, налета, вредителей, увядания, ожогов). Если растение визуально выглядит здоровым, ты ОБЯЗАН расписать 3-5 главных скрытых сезонных угроз, болезней или вредителей, которым сильнее всего подвержен именно этот конкретный вид.

**3. Пошаговый план лечения и профилактики:** Список конкретных коммерческих препаратов (фунгициды, инсектициды, акарициды) и чёткие сроки обработок по сезонам (ранняя весна, вегетация, осень). 
СТРОГОЕ ПРАВИЛО БЕЗОПАСНОСТИ: Для лиственных и цветущих культур категорически запрещено рекомендовать медьсодержащие препараты (ХОМ, Бордоская смесь) в период раскрытия бутонов и активного цветения, чтобы не сжечь лепестки (в этот период заменяй их на системные фунгициды вроде Хорус или Скор). Для хвойных растений и газонов используй стандартные сезонные регламенты.

**4. Рекомендации по комплексному уходу:** Требования к режиму полива, сезонным подкормкам (какие элементы нужны весной, летом и осенью), правила обрезки/стрижки и подготовки к зиме конкретно для этого типа растений.`;
        
        const aiResponse = await fetch('https://gen.pollinations.ai/v1/chat/completions', {
            method: 'POST',
            headers: { 
                'Content-Type': 'application/json',
                'Authorization': `Bearer ${process.env.POLLINATIONS_API_KEY}`
            },
            body: JSON.stringify({
                messages: [
                    {
                        role: 'user',
                        content: [
                            { type: 'text', text: systemInstructions },
                            { type: 'image_url', image_url: { url: image } }
                        ]
                    }
                ],
                model: 'openai-fast' // Прописываем Gemini 2.5 Flash Lite из выпадающего списка
            })
        });

        if (!aiResponse.ok) {
            const errorText = await aiResponse.text();
            throw new Error(`Ошибка нейросети: ${errorText}`);
        }

        const responseData = await aiResponse.json();
        const aiText = responseData.choices[0].message.content;
        
        return res.status(200).send(aiText);

    } catch (error) {
        console.error('Ошибка на бэкенде диагностики:', error);
        return res.status(500).json({ error: 'Внутренняя ошибка сервера при анализе' });
    }
}
