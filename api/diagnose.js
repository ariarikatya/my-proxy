export default async function handler(req, res) {
    res.setHeader('Access-Control-Allow-Credentials', true);
    res.setHeader('Access-Control-Allow-Origin', '*'); 
    res.setHeader('Access-Control-Allow-Methods', 'GET,OPTIONS,PATCH,DELETE,POST,PUT');
    res.setHeader('Access-Control-Allow-Headers', 'X-CSRF-Token, X-Requested-With, Accept, Accept-Version, Content-Length, Content-MD5, Content-Type, Date, X-Api-Version, Authorization');

    if (req.method === 'OPTIONS') {
        return res.status(200).end(); 
    }

    if (req.method !== 'POST') {
        return res.status(405).json({ error: 'Method not allowed' });
    }

    try {
        // 🔥 Достаем image и переданный вопрос question
        const { image, question } = req.body;
        if (!image) {
            return res.status(400).json({ error: 'Image data is required' });
        }

        let systemInstructions = "";

        // 🔥 Если пользователь задал конкретный вопрос
        if (question && question.trim() !== "") {
            systemInstructions = `Ты — высококвалифицированный эксперт-фитопатолог и агроном ландшафтной компании 'Анемон АГРО'. 
Перед тобой находится фотография растения, загруженная пользователем. Пользователь внимательно изучил это изображение и задал к нему конкретный вопрос.

КОНТЕКСТ ЗАПРОСА:
- Изображение для анализа: [Передано в запросе ниже]
- Конкретный вопрос пользователя по этому фото: "${question}"

Твоя задача — внимательно исследовать прикрепленное фото растения (листья, стебли, почву, признаки болезней или вредителей) и дать развернутый, экспертный ответ строго по теме заданного вопроса, опираясь на то, что ты видишь на изображении.

Правила ответа:
1. Отвечай сразу по делу, без приветствий и лишней воды.
2. Текст должен быть структурированным, понятным, используй списки, если даешь пошаговые рекомендации.
3. Не используй маркеры блоков [БЛОК_1] и [БЛОК_2], пиши сплошным красивым текстом с выделением важных моментов жирным шрифтом через **.
4. По препаратам используй строго коммерческие торговые названия (никаких действующих веществ в скобках). Если советуешь химию, пиши её правильно (фунгициды от болезней, инсектициды от насекомых, акарициды от клещей).`;
        } else {
            // Стандартные инструкции фитопатолога, если вопроса нет (обычный скан)
            systemInstructions = `Ты — высококвалифицированный и строгий фитопатолог ландшафтной компании 'Анемон АГРО'. Твоя задача — провести точную диагностику по фотографии растения.
Ты должен строго следовать формату ответа, используя маркеры [БЛОК_1] и [БЛОК_2]. Не пиши никаких приветствий и вступлений.

КРИТИЧЕСКОЕ ПРАВИЛО ИДЕНТИФИКАЦИИ РАСТЕНИЯ:
Перед тем как определялять болезни, проведи тщательный ботанический анализ: посмотри на форму листьев, их жилкование, расположение на стебле (очередное, супротивное, мутовчатое) и наличие почек. Ты обязан определить конкретный род и вид растения максимально точно. Не путай рододендроны, барбарисы, пироканты и другие кустарники только из-за схожих пятен на листьях!

КРИТИЧЕСКИЕ ПРАВИЛА ПО ПРЕПАРАТАМ И ХИМИИ:
1. Запрещено выдумывать или писать в скобках действующие вещества препаратов (никаких "Хорус (cyprodinil)" или "Скор (tebuconazole)"). Пиши только коммерческие торговые названия.
2. Никогда не путай категории препаратов: 
   - От болезней/грибков (пятнистости, ржавчина, гнили) назначай только ФУНГИЦИДЫ (например: Хорус, Скор, Топаз, Раёк, Квадрис). Во время цветения медь использовать запрещено!
   - От клещей (паутинный клещ) назначай только АКАРИЦИДЫ или ИНСЕКТОАКАРИЦИДЫ (например: Фитоверм, Актеллик, Вертимек, Масай). Никогда не называй Скор или Хорус средством от клещей — это грубая ошибка!
   - От насекомых-вредителей (тля, щитовка, трипсы) назначай ИНСЕКТИЦИДЫ (например: Актара, Искра, Конфидор).

ФОРМАТ ОТВЕТА (ЗАПРЕЩЕНО использовать знаки дефиса "-" в начале строк плана, пиши только цифрами):

[БЛОК_1]
Название: [Конкретное русское название / Обиходное (Род/Семейство на латыни)]
Инфо: [Короткое описание растения, его особенности или статус на фото строго в 2 строчки]

[БЛОК_2]
ОБНАРУЖЕНЫ УГРОЗЫ ‼️🚨
Симптомы: [перечисление через запятую]
Болезни и вредители: [список из 2-3 главных угроз]
Пошаговый план лечения:
1) [Действие по обрезке/изоляции]
2) [Применение фунгицида от болезней, если они есть. Помни: во время цветения медь заменяй на Хорус или Скор]
3) [Применение акарицида/инсектицида, если обнаружены клещи или насекомые]
4) [Профилактика и уход]
Kраткий уход: [1-2 предложения]

[Если растение абсолютно здоровое, вместо всего текста в БЛОК_2 пиши строго одну фразу]:
РАСТЕНИЕ ЗДОРОВО ✅. Явных признаков заболеваний или вредителей не обнаружено. Продолжайте стандартный уход.`;
        }
        
        const aiResponse = await fetch('https://gen.pollinations.ai/v1/chat/completions', {
            method: 'POST',
            headers: { 
                'Content-Type': 'application/json',
                'Authorization': `Bearer ${process.env.POLLINATIONS_API_KEY}`
            },
            body: JSON.stringify({
                messages: [
                    {
                        role: 'user',
                        content: [
                            { type: 'text', text: systemInstructions },
                            { type: 'image_url', image_url: { url: image } }
                        ]
                    }
                ],
                model: 'gpt-5.4-mini'
            })
        });

        if (!aiResponse.ok) {
            const errorText = await aiResponse.text();
            throw new Error(`Ошибка нейросети: ${errorText}`);
        }

        const responseData = await aiResponse.json();
        const aiText = responseData.choices[0].message.content;
        
        return res.status(200).send(aiText);

    } catch (error) {
        console.error('Ошибка на бэкенде диагностики:', error);
        return res.status(500).json({ error: 'Внутренняя ошибка сервера при анализе' });
    }
}
